# Mots dérivés des codes neutres renvoyés par metrics.regime_read (pas de mot
# figé dans une langue à la source, cf. commentaire dans regime_read).
_PRESSURE_WORD = {
    "es": {"sell": "vendedora", "buy": "compradora"},
    "fr": {"sell": "vendeuse", "buy": "acheteuse"},
    "en": {"sell": "selling", "buy": "buying"},
}
_BIAS_WORD = {
    "es": {"down": "bajista", "up": "alcista"},
    "fr": {"down": "baissier", "up": "haussier"},
    "en": {"down": "downward", "up": "upward"},
}


def t(lang: str, key: str, **fmt) -> str:
    s = TR.get(lang, TR["es"]).get(key, key)
    return s.format(**fmt) if fmt else s


def regime_text(lang: str, regime: dict) -> str:
    """Compone el texto de lectura de régimen a partir del dict `metrics.regime_read`."""
    p = regime["params"]
    words = {
        "sens_delta": p["sens_delta"],
        "pression": _PRESSURE_WORD.get(lang, _PRESSURE_WORD["es"])[p["pression_code"]],
        "biais": _BIAS_WORD.get(lang, _BIAS_WORD["es"])[p["biais_code"]],
    }
    return t(lang, regime["i18n_key"], **words)


def wall_labels(levels) -> dict:
    """Clasificación no direccional de los muros de gamma: GEX1..GEXn por |GEX|.

    Los niveles direccionales (Call Wall por encima del spot, Put Support por
    debajo) se calculan aparte con metrics.key_levels.
    """
    if levels is None or len(levels) == 0:
        return {}
    return {lv.strike: f"GEX{lv.rank}" for lv in levels.itertuples()}
